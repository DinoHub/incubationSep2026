#!/usr/bin/env python3
"""Add OAuth 2.1 authentication and per-tool roles to an existing MCP server
project generated by the mcp-server-scaffold skill.

The mechanical half is automated here: the token verifier, the Keycloak realm,
the full-stack auth test, the container wiring. What is left for a person or a
model is the half that needs judgment — which role each tool requires.

    python add_auth.py --dir ./file-tools

Existing files are backed up to <name>.pre-auth before being replaced. Run with
--dry-run first if you want to see the plan without touching anything.
"""

from __future__ import annotations

import argparse
import re
import shutil
import sys
from pathlib import Path

try:
    import yaml
except ImportError:
    yaml = None

ASSETS = Path(__file__).resolve().parent.parent / "assets"

# Files the scaffold always produces. Their absence means this is not a
# scaffolded project, and patching blindly would make a mess.
REQUIRED = ("http_server.py", "test_server.py", "Dockerfile", "docker-compose.yaml")


def die(msg: str) -> None:
    print(f"error: {msg}", file=sys.stderr)
    raise SystemExit(1)


def render(template: str, subs: dict[str, str]) -> str:
    text = (ASSETS / template).read_text(encoding="utf-8")
    for k, v in subs.items():
        text = text.replace("{{" + k + "}}", v)
    left = re.findall(r"\{\{[A-Z_]+\}\}", text)
    if left:
        die(f"{template}: unsubstituted placeholders {sorted(set(left))}")
    return text


def find_server_module(root: Path) -> str:
    """The scaffold's http_server.py imports the server module by name."""
    m = re.search(r"^from\s+(\w+)\s+import\s+mcp",
                  (root / "http_server.py").read_text(encoding="utf-8"), re.M)
    if not m:
        die("could not find the server module name in http_server.py — is this a scaffolded project?")
    return m.group(1)


def find_port(root: Path) -> str:
    text = (root / "Dockerfile").read_text(encoding="utf-8")
    m = re.search(r"^\s*PORT=(\d+)", text, re.M) or re.search(r"^EXPOSE\s+(\d+)", text, re.M)
    return m.group(1) if m else "8000"


def find_image_name(root: Path) -> str:
    m = re.search(r"^\s*image:\s*([\w.\-/]+):latest",
                  (root / "docker-compose.yaml").read_text(encoding="utf-8"), re.M)
    return m.group(1) if m else "mcp-server"


def backup(path: Path, dry: bool) -> None:
    if path.exists():
        dest = path.with_suffix(path.suffix + ".pre-auth")
        print(f"  backup {path.name} -> {dest.name}")
        if not dry:
            shutil.copy2(path, dest)


def service_block(lines: list[str], name: str) -> tuple[int, int] | None:
    """Line range of one compose service, from its header to the next one."""
    start = next((i for i, l in enumerate(lines) if l.rstrip() == f"  {name}:"), None)
    if start is None:
        return None
    for j in range(start + 1, len(lines)):
        if re.match(r"^  \S", lines[j]) or re.match(r"^\S", lines[j]):
            return start, j
    return start, len(lines)


def patch_compose(root: Path, subs: dict[str, str], dry: bool) -> bool:
    """Insert the auth env vars and append the keycloak/test-auth services.

    Text insertion rather than parse-and-re-emit, because a YAML round trip
    would strip every comment in the file. The result is validated as YAML
    before it is written, and the whole thing is skipped — with a snippet
    written out for a human to merge — if the file does not have the shape the
    scaffold produces.
    """
    path = root / "docker-compose.yaml"
    lines = path.read_text(encoding="utf-8").splitlines(keepends=True)

    if service_block(lines, "mcp-server") is None:
        return False

    def insert_env(buf: list[str], service: str, template: str) -> list[str]:
        """Add env vars to a service, creating the environment block if absent."""
        sp = service_block(buf, service)
        if sp is None:
            return buf
        s, e = sp
        env = render(template, subs).splitlines(keepends=True)
        idx = next((i for i in range(s, e) if buf[i].rstrip() == "    environment:"), None)
        if idx is None:
            return buf[:s + 1] + ["    environment:\n"] + env + buf[s + 1:]
        return buf[:idx + 1] + env + buf[idx + 1:]

    new = insert_env(lines, "mcp-server", "compose-env.yaml.tmpl")
    # The in-process test imports the server module, which now builds
    # AuthSettings at import time and so needs an issuer string present even
    # though it never contacts one.
    new = insert_env(new, "test", "compose-env-test.yaml.tmpl")

    text = "".join(new).rstrip() + "\n" + render("compose-services.yaml.tmpl", subs)
    if yaml is not None:
        try:
            parsed = yaml.safe_load(text)
        except yaml.YAMLError as exc:
            die(f"the patched docker-compose.yaml is not valid YAML: {exc}")
        for expected in ("keycloak", "test-auth", "mcp-server"):
            if expected not in parsed.get("services", {}):
                die(f"the patched docker-compose.yaml lost the {expected!r} service")
    backup(path, dry)
    print("  patch  docker-compose.yaml (auth env on mcp-server, + keycloak and test-auth)")
    if not dry:
        path.write_text(text, encoding="utf-8")
    return True


def patch_requirements(root: Path, dry: bool) -> None:
    path = root / "requirements.txt"
    text = path.read_text(encoding="utf-8") if path.exists() else ""
    if re.search(r"^\s*PyJWT", text, re.M | re.I):
        print("  skip   requirements.txt (PyJWT already listed)")
        return
    # PyJWT arrives as a transitive dependency of mcp today, but relying on
    # that would break the day mcp drops it. The cryptography extra is what
    # supplies RS256 verification.
    addition = 'PyJWT[crypto]>=2.10   # RS256 verification of the issuer\'s tokens\n'
    print("  patch  requirements.txt (+ PyJWT[crypto])")
    if not dry:
        path.write_text(text.rstrip() + "\n" + addition, encoding="utf-8")


def patch_dockerfile(root: Path, dry: bool) -> None:
    path = root / "Dockerfile"
    text = path.read_text(encoding="utf-8")
    if "auth.py" in text:
        print("  skip   Dockerfile (auth.py already copied)")
        return
    m = re.search(r"^COPY .*test_server\.py.*$", text, re.M)
    if not m:
        die("could not find the COPY line naming test_server.py in the Dockerfile")
    line = m.group(0)
    new_line = line + "\nCOPY auth.py test_auth.py ./"
    backup(path, dry)
    print("  patch  Dockerfile (+ COPY auth.py test_auth.py)")
    if not dry:
        path.write_text(text.replace(line, new_line), encoding="utf-8")



