def patch_readme(root, subs, dry_run):
    """Correct the scaffold README's pre-auth claims. Reports what it could not find."""
    path = root / "README.md"
    if not path.exists():
        print("  skip   README.md (not found) — write the auth section in by hand")
        return
    text = path.read_text(encoding="utf-8")
    applied, missed = [], []
    for label, old, new in README_PATCHES:
        for k, v in subs.items():
            old = old.replace("{{" + k + "}}", v)
            new = new.replace("{{" + k + "}}", v)
        if old in text:
            text = text.replace(old, new, 1)
            applied.append(label)
        else:
            missed.append(label)
    if not dry_run and applied:
        path.write_text(text, encoding="utf-8")
    print(f"  patch  README.md ({len(applied)} of {len(README_PATCHES)} pre-auth claims corrected)")
    for label in missed:
        print(f"         COULD NOT FIND {label} — check README.md says the port is "
              f"authenticated and that first-run uses --profile dev")


def main() -> int:
    p = argparse.ArgumentParser(description=__doc__,
                                formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--dir", required=True, help="The scaffolded project to add auth to.")
    p.add_argument("--realm", help="Keycloak realm name. Default: the image name.")
    p.add_argument("--role-read", default="tools:read", help="Role for read-only tools.")
    p.add_argument("--role-write", default="tools:write", help="Role for state-changing tools.")
    p.add_argument("--keycloak-port", default="8080", help="Host port for Keycloak (default: 8080).")
    p.add_argument("--dry-run", action="store_true", help="Print the plan, change nothing.")
    p.add_argument("--callback-port", type=int, default=8123,
                   help="Port the MCP host listens on for the OAuth callback (default: 8123). "
                        "Registered as a redirect URI in the realm; pass the same value to "
                        "`claude mcp add --callback-port`.")
    p.add_argument("--force", action="store_true", help="Proceed even if auth.py already exists.")
    args = p.parse_args()

    root = Path(args.dir).resolve()
    if not root.is_dir():
        die(f"{root} is not a directory")
    missing = [f for f in REQUIRED if not (root / f).exists()]
    if missing:
        die(f"{root.name} does not look like a scaffolded MCP project — missing {missing}. "
            f"Generate one with the mcp-server-scaffold skill first.")
    if (root / "auth.py").exists() and not args.force:
        die("auth.py already exists — this project already has auth. "
            "Add a tool's role check by hand, or pass --force to regenerate the auth files.")

    module = find_server_module(root)
    port = find_port(root)
    image = find_image_name(root)
    realm = args.realm or image
    subs = {
        "SERVER_NAME": module.replace("_server", "").replace("_", " ").title().replace(" ", ""),
        "MODULE": module,
        "PORT": port,
        "IMAGE_NAME": image,
        "SERVER_SLUG": image,
        # What the scaffold README calls the server in `claude mcp add`. It is
        # the image name without the mcp- prefix, not the image name itself.
        "README_SLUG": image[4:] if image.startswith("mcp-") else image,
        "REALM": realm,
        "ROLE_READ": args.role_read,
        "ROLE_WRITE": args.role_write,
        "KEYCLOAK_PORT": str(args.keycloak_port),
        "CLIENT_READER": "agent-reader",
        "CLIENT_WRITER": "agent-writer",
        "SECRET_READER": "reader-dev-secret",
        "SECRET_WRITER": "writer-dev-secret",
        # The interactive identity an MCP host signs in through. Separate from
        # the two machine clients because it is public (no secret, PKCE
        # instead) and because it is the only one that issues refresh tokens.
        "CLIENT_OAUTH": "claude-code",
        "CALLBACK_PORT": str(args.callback_port),
        "USER_READER": "dev-reader",
        "USER_WRITER": "dev-writer",
        "PASSWORD_READER": "dev-reader-password",
        "PASSWORD_WRITER": "dev-writer-password",
    }

    print(f"Project: {root}")
    print(f"  server module: {module}.py   port: {port}   image: {image}   realm: {realm}")
    print(f"  roles: {args.role_read} (read), {args.role_write} (write)")
    print()

    new_files = {
        "auth.py": "auth.py.tmpl",
        "test_auth.py": "test_auth.py.tmpl",
        "healthcheck.py": "healthcheck.py.tmpl",
        ".env.example": "env.example.tmpl",
        "keycloak/realm-export.json": "realm-export.json.tmpl",
    }
    for name, tmpl in new_files.items():
        target = root / name
        if target.exists():
            backup(target, args.dry_run)
        print(f"  write  {name}")
        if not args.dry_run:
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_text(render(tmpl, subs), encoding="utf-8")

    patch_requirements(root, args.dry_run)
    patch_dockerfile(root, args.dry_run)
    merged = patch_compose(root, subs, args.dry_run)
    if not merged:
        snippet = root / "docker-compose.auth-snippet.yaml"
        print(f"  WRITE  {snippet.name} — could not find an 'mcp-server' service to patch, "
              f"so the additions were written here for you to merge by hand")
        if not args.dry_run:
            snippet.write_text(render("compose-env.yaml.tmpl", subs)
                               + render("compose-services.yaml.tmpl", subs), encoding="utf-8")

    patch_readme(root, subs, args.dry_run)

    # Reference copies, for the model or person doing the remaining edits.
    for name, tmpl in (("test_server_identity_snippet.py", "test_server_identity_snippet.py.tmpl"),
                       ("README-auth-section.md", "README-auth.md.tmpl")):
        print(f"  write  {name} (reference — delete once you have used it)")
        if not args.dry_run:
            (root / name).write_text(render(tmpl, subs), encoding="utf-8")

    print(f"""
Still to do by hand — these need judgment, not templating:

  1. {module}.py — wire the verifier in:
         from auth import JWKSTokenVerifier, auth_settings, require_role
         mcp = MCPServer(..., token_verifier=JWKSTokenVerifier(), auth=auth_settings())
     then add require_role("{args.role_read}") or require_role("{args.role_write}")
     as the first line of every tool, and say so in the instructions string.

  2. test_server.py — the in-process test has no identity now, so every guarded
     tool would fail. Fold in test_server_identity_snippet.py.

  3. test_auth.py — fill in EXPECTATIONS with one row per tool.

  4. README.md — append README-auth-section.md and fill in its role table. The
     pre-auth claims elsewhere in it were corrected above; check the report for
     any the patcher could not find.

Then: docker compose --profile dev up -d --build
      docker compose run --rm test                     # roles, in-process
      docker compose run --rm test-auth                 # tokens, over HTTP
""")
    if args.dry_run:
        print("(dry run — nothing was written)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
